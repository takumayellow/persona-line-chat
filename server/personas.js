function nameClause(userName, honorific) {
  if (!userName) {
    return "相手の名前はまだ分かりません。名前で呼ばず「キミ」などで話してください。";
  }
  const suffix = honorific && honorific !== "呼び捨て" ? honorific : "";
  return `相手の名前は「${userName}」です。呼びかけるときは必ず「${userName}${suffix}」と呼んでください(名前だけ・別の呼称は使わない)。`;
}

